#!/usr/bin/env python3
"""Regenerate the SI model catalogue table from the released data tables.

    python scripts/build_inventory_table.py

One row per measurement (a hybrid model contributes a row per reasoning
configuration), with the fitted CC and its 95% interval from scc.csv and the
static metadata from registry.csv.
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
OUT = REPO_ROOT / "paper" / "generated" / "model_inventory_table_si.tex"


def esc(text: str) -> str:
    return text.replace("_", "\\_").replace("%", "\\%").replace("#", "\\#")


def fmt_params(row: dict) -> str:
    total, active = row.get("total_params_b"), row.get("active_params_b")
    if not total:
        return "--"
    if active and active != total:
        return f"{float(total):g}B / {float(active):g}B"
    return f"{float(total):g}B"


def fmt_ctx(row: dict) -> str:
    value = row.get("context_length")
    if not value or not value.isdigit():
        return "--"
    n = int(value)
    return f"{n // 1000}k" if n < 1_000_000 else f"{n / 1e6:g}M"


def breakable(name: str) -> str:
    """Let long model ids wrap in the p{} column: typewriter hyphens are not
    break points, so allow a break after each one."""
    return name.replace("-", "-\\allowbreak{}")


def main() -> int:
    registry = {r["run_key"]: r for r in csv.DictReader(
        (REPO_ROOT / "results" / "counting-data" / "registry.csv").open(encoding="utf-8"))}
    rows = list(csv.DictReader(
        (REPO_ROOT / "results" / "counting-data" / "scc.csv").open(encoding="utf-8")))
    rows.sort(key=lambda r: (registry[r["run_key"]].get("lab") or "", r["run_key"]))

    lines = [
        "% Generated by scripts/build_inventory_table.py -- do not edit by hand.",
        "\\begin{longtable}{@{}p{4.6cm}p{1.5cm}p{2.0cm}p{1.1cm}p{1.0cm}p{1.9cm}@{}}",
        "\\caption{\\textbf{Full model catalogue.} One row per measurement; hybrid",
        "models appear once per reasoning configuration. CC is the fitted transition",
        "with its calibrated interval (nominal 95\\%; Appendix~\\ref{app:estimation}); capacities marked $\\geq$ are lower bounds, set by",
        "the output budget rather than by a counting failure. Parameter counts give, or unresolved where the bound column says so.",
        "total and, for mixture models, active parameters. Metadata are drawn from the",
        "OpenRouter catalogue and public documentation.}\\label{tab:model_inventory}\\\\",
        "\\toprule",
        "Measurement & Params & Context & CC & 95\\% CI & Bounded by \\\\",
        "\\midrule",
        "\\endfirsthead",
        "\\toprule",
        "Measurement & Params & Context & CC & 95\\% CI & Bounded by \\\\",
        "\\midrule",
        "\\endhead",
        "\\bottomrule",
        "\\endfoot",
    ]
    for r in rows:
        reg = registry[r["run_key"]]
        name = esc(r["run_key"].split("/", 1)[-1].replace("#", " #"))
        cc = r["scc"]
        # the bound column and the >= marker must come from the same fit
        bound = r.get("scc_bound_by") or reg.get("cc_bound_by") or "--"
        if r["censored"] == "True":
            bound = "unresolved"
        prefix = "$\\geq$" if r["sufficiency"] in ("budget_bound",) or r["censored"] == "True" else ""
        ci = f"[{r['scc_ci_low']}, {r['scc_ci_high']}]" if r["censored"] != "True" else "--"
        lines.append(
            f"\\texttt{{{breakable(name)}}} & {fmt_params(reg)} & {fmt_ctx(reg)} & "
            f"{prefix}{cc} & {ci} & {esc(bound)} \\\\"
        )
    lines.append("\\end{longtable}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}  ({len(rows)} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
