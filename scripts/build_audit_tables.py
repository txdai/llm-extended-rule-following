#!/usr/bin/env python3
"""Regenerate the instruction-following audit tables for Appendix E.

    python -m counting.analysis.instruction_following_audit   # refresh cases
    python scripts/build_audit_tables.py
"""

from __future__ import annotations

import csv
import glob
import json
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
CASES = REPO_ROOT / "results" / "non_single_number_responses_cases.csv"
OUT = REPO_ROOT / "paper" / "generated" / "audit_tables.tex"

SNIPPETS = [
    ("Step-by-step counting", "claude-sonnet-5", 55,
     "Let me count them one by one.\\textbackslash n\\textbackslash n55"),
    ("Code / markdown output", "gemini-3-flash-preview", 303,
     "\\textasciigrave\\textasciigrave\\textasciigrave json 303 \\textasciigrave\\textasciigrave\\textasciigrave"),
    ("Prompt echo", "mistral-medium-3-5", 49,
     "a, a, a, a, a, a, a a, a, a, \\ldots{} (sequence copied back)"),
    ("Leaked reasoning markup", "qwen3.5-flash-02-23", 5,
     "Thinking Process: 1. Analyze the Request: Task: Count occurrences\\ldots"),
    ("Mixed numeric format", "deepseek-v4-pro-0813", 110, "110.110"),
    ("Prose / instruction leakage", "minimax-m2-her", 97,
     "87 \\textbackslash n user name=talkior \\textbackslash n No. Try again."),
]


def esc(text: str) -> str:
    return text.replace("_", "\\_").replace("%", "\\%").replace("#", "\\#")


def main() -> int:
    cases = list(csv.DictReader(CASES.open(encoding="utf-8")))
    total = 0
    per_model = Counter()
    for path in glob.glob(str(REPO_ROOT / "results" / "counting-data" / "trials" / "*.jsonl")):
        for line in open(path, encoding="utf-8"):
            if not line.strip():
                continue
            row = json.loads(line)
            if row.get("phase") == "scan":
                total += 1
                per_model[row.get("model")] += 1

    categories = Counter(c["category"] for c in cases)
    by_model = Counter(c["model"] for c in cases)

    lines = [
        "% Generated by scripts/build_audit_tables.py -- do not edit by hand.",
        "\\begin{table}[htbp]\\centering\\scriptsize",
        f"\\caption{{Distribution of non-single-number responses across all "
        f"{total:,} scan probes ({len(cases):,} deviating responses, "
        f"{len(cases)/total*100:.1f}\\%).}}",
        "\\label{tab:audit_categories}",
        "\\begin{tabular}{@{}l r r@{}}",
        "\\toprule",
        "Category & Count & Share of probes \\\\",
        "\\midrule",
    ]
    for cat, n in categories.most_common():
        lines.append(f"{esc(cat)} & {n:,} & {n/total*100:.2f}\\% \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]

    lines += [
        "\\begin{table}[htbp]\\centering\\scriptsize",
        "\\caption{Models most frequently deviating from the single-integer format,",
        "with each model's deviations as a share of its own probes.}",
        "\\label{tab:audit_models}",
        "\\begin{tabular}{@{}l r r@{}}",
        "\\toprule",
        "Model & Deviations & Share of own probes \\\\",
        "\\midrule",
    ]
    for model, n in by_model.most_common(10):
        own = per_model.get(model, 0) or 1
        lines.append(f"\\texttt{{{esc(model.split('/')[-1])}}} & {n} & {n/own*100:.0f}\\% \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]

    lines += [
        "\\begin{table}[htbp]\\centering\\scriptsize",
        "\\caption{Representative deviating responses; L is the probed length.}",
        "\\label{tab:audit_snippets}",
        "\\begin{tabular}{@{}l l r p{5.0cm}@{}}",
        "\\toprule",
        "Category & Model & L & Response \\\\",
        "\\midrule",
    ]
    for cat, model, length, snippet in SNIPPETS:
        lines.append(f"{cat} & \\texttt{{{esc(model)}}} & {length} & {snippet} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
