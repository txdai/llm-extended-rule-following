#!/usr/bin/env python3
"""Emit the anchored-execution control table from the state-solo records.

    python scripts/report_anchored_control.py

Records are evaluated to a uniform probe ceiling (320 for the anchored levels,
1000 in steps of 50 for lookup) and fitted with the same estimator as every
counting measurement; measurements not resolved at the ceiling are reported as
lower bounds.
"""

from __future__ import annotations

import json
import sys
from glob import glob
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from counting.analysis.capacity import fit_transition  # noqa: E402

OUT = REPO_ROOT / "paper" / "appendix" / "anchored_control_table.tex"
CEILINGS = {1: 1000, 2: 320, 3: 320, 4: 320}
MODELS = [
    ("anthropic__claude-sonnet-5__think", "\\texttt{claude-sonnet-5}", 89),
    ("openai__gpt-5.6-terra__think", "\\texttt{gpt-5.6-terra}", 115),
    ("google__gemini-3.7-flash", "\\texttt{gemini-3.7-flash}", 351),
]
LEVEL_NAMES = {1: "Lookup", 2: "Pointer chase", 3: "Running total", 4: "Automaton"}


def cell(level: int, stem: str) -> str:
    path = REPO_ROOT / "results" / "state-solo" / f"L{level}" / "trials" / f"{stem}.jsonl"
    recs = [json.loads(l) for l in path.open() if l.strip()]
    recs = [r for r in recs if r.get("phase") == "scan"
            and r["center_length"] <= CEILINGS[level]]
    recs.sort(key=lambda r: r["center_length"])
    fit = fit_transition(
        [r["center_length"] for r in recs],
        [bool(r.get("exact_match")) for r in recs],
        [r.get("parsed") is None for r in recs],
    )
    cap = f"$\\geq {fit.scc}$" if fit.censored else str(fit.scc)
    return f"{cap} ({fit.p_stable:.2f})"


lines = [
    "% Generated by scripts/report_anchored_control.py -- do not edit by hand.",
    "\\begin{table}[htbp]",
    "\\centering",
    "\\scriptsize",
    "\\caption{Anchored-execution control. Each cell gives the fitted capacity of",
    "one subsidiary task, with the stable-regime accuracy in parentheses;",
    "$\\geq$ marks measurements that had not collapsed at the probe ceiling.",
    "Counting capacities for the same three models are 89, 115, and 351.}",
    "\\label{tab:anchored_control}",
    "\\begin{tabular}{@{}l l r r r@{}}",
    "\\toprule",
    "Level & Task & " + " & ".join(label for _, label, _ in MODELS) + " \\\\",
    "\\midrule",
]
for level in (1, 2, 3, 4):
    cells = " & ".join(cell(level, stem) for stem, _, _ in MODELS)
    lines.append(f"{level} & {LEVEL_NAMES[level]} & {cells} \\\\")
lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT}")
